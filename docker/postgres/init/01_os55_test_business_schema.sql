CREATE TABLE IF NOT EXISTS local (
    id_local VARCHAR(64) PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS surveillance (
    id_surveillance BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_local VARCHAR(64) NOT NULL REFERENCES local(id_local),
    id_fiche VARCHAR(64) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_surveillance_local_fiche ON surveillance (id_local, id_fiche);

INSERT INTO local (id_local) VALUES
    ('LOCAL_OK'),
    ('LOCAL_EMPTY'),
    ('LOCAL_MULTI'),
    ('LOCAL_ROLLBACK'),
    ('LOCAL_CONCURRENT')
ON CONFLICT (id_local) DO NOTHING;

INSERT INTO surveillance (id_local, id_fiche)
SELECT v.id_local, v.id_fiche
FROM (VALUES
    ('LOCAL_OK', 'FICHE_OK'),
    ('LOCAL_MULTI', 'FICHE_A'),
    ('LOCAL_MULTI', 'FICHE_B'),
    ('LOCAL_ROLLBACK', 'FICHE_ROLLBACK'),
    ('LOCAL_CONCURRENT', 'FICHE_CONCURRENT')
) AS v(id_local, id_fiche)
WHERE NOT EXISTS (
    SELECT 1 FROM surveillance s WHERE s.id_local = v.id_local AND s.id_fiche = v.id_fiche
);
