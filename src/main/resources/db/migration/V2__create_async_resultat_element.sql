CREATE TABLE async_resultat_element (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requete_id BIGINT NOT NULL,
    num BIGINT NOT NULL,
    code_retour VARCHAR(8) NOT NULL,
    resultat_json TEXT NOT NULL,
    date_creation TIMESTAMP NOT NULL,
    CONSTRAINT fk_async_resultat_element_requete FOREIGN KEY (requete_id) REFERENCES async_request(id),
    CONSTRAINT uk_async_resultat_element_requete_num UNIQUE (requete_id, num)
);

CREATE INDEX idx_async_resultat_element_requete ON async_resultat_element (requete_id);
