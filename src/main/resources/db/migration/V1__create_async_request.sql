CREATE TABLE async_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL,
    client_id VARCHAR(255) NOT NULL,
    code_os INTEGER NOT NULL,
    status VARCHAR(32) NOT NULL,
    input_file_path VARCHAR(1024),
    output_file_path VARCHAR(1024),
    date_creation TIMESTAMP NOT NULL,
    date_mise_a_jour TIMESTAMP NOT NULL,
    date_debut TIMESTAMP,
    date_fin TIMESTAMP,
    declared_element_count BIGINT,
    processed_element_count BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_async_request_uuid UNIQUE (uuid)
);

CREATE INDEX idx_async_request_status ON async_request (status);
CREATE INDEX idx_async_request_client_uuid ON async_request (client_id, uuid);
