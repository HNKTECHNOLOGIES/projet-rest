CREATE TABLE local (
    id_local VARCHAR(64) PRIMARY KEY
);

CREATE TABLE surveillance (
    id_surveillance BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_local VARCHAR(64) NOT NULL,
    id_fiche VARCHAR(64) NOT NULL,
    CONSTRAINT fk_surveillance_local FOREIGN KEY (id_local) REFERENCES local(id_local)
);

CREATE INDEX idx_surveillance_local_fiche ON surveillance (id_local, id_fiche);
